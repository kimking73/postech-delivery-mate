-- SV1: 핵심 테이블 (아키텍처 §2-2)
-- 공통: 모든 테이블에 RLS를 켠다. 정책은 SV3 이후 마이그레이션에서 추가하므로
--       이 시점에는 anon/authenticated의 직접 접근이 모두 거부된다(RPC·service_role만).
-- 시각 컬럼은 모두 timestamptz(UTC 저장).
-- 나머지 테이블(reports, blocks, sanctions, push_tokens, payout_accounts, ...)은 SV3에서 만든다.

-- ---------------------------------------------------------------------------
-- enum
-- ---------------------------------------------------------------------------
create type public.post_status       as enum ('open', 'closed', 'completed', 'canceled');
create type public.participant_role  as enum ('host', 'member');
create type public.participant_state as enum ('joined', 'left', 'dropped', 'kicked');
create type public.paid_state        as enum ('none', 'sent', 'confirmed');
create type public.message_type      as enum ('text', 'system');

-- ---------------------------------------------------------------------------
-- zones: 생활 구역
-- ---------------------------------------------------------------------------
create table public.zones (
  id         smallint generated by default as identity primary key,
  name       text     not null unique,
  sort_order smallint not null default 0,
  is_active  boolean  not null default true
);

-- ---------------------------------------------------------------------------
-- categories
-- ---------------------------------------------------------------------------
create table public.categories (
  id         smallint generated by default as identity primary key,
  name       text     not null unique,
  emoji      text,
  sort_order smallint not null default 0
);

-- ---------------------------------------------------------------------------
-- pickup_places: 픽업 장소 프리셋
-- ---------------------------------------------------------------------------
create table public.pickup_places (
  id         smallint generated by default as identity primary key,
  zone_id    smallint not null references public.zones (id),
  name       text     not null,
  sort_order smallint not null default 0,
  is_active  boolean  not null default true,
  unique (zone_id, name),
  -- posts가 (pickup_place_id, zone_id)로 참조해 "다른 구역의 픽업 장소"를 막는다.
  unique (id, zone_id)
);

-- ---------------------------------------------------------------------------
-- profiles: auth.users와 1:1. 메일은 저장하지 않는다(auth.users에만 둔다).
-- ---------------------------------------------------------------------------
create table public.profiles (
  id                  uuid primary key references auth.users (id) on delete cascade,
  nickname            text not null unique
                      constraint profiles_nickname_format
                      check (char_length(nickname) between 2 and 12
                             and nickname ~ '^[가-힣a-zA-Z0-9_]+$'),
  home_zone_id        smallint references public.zones (id),
  verified_at         timestamptz,
  noshow_count        smallint not null default 0 check (noshow_count >= 0),
  notify_chat         boolean not null default true,
  notify_post_events  boolean not null default true,
  notify_marketing    boolean not null default false,
  eula_agreed_at      timestamptz,
  terms_agreed_at     timestamptz,
  is_admin            boolean not null default false,  -- RPC만 변경(직접 UPDATE 불가: RLS/권한에서 막음)
  deleted_at          timestamptz,
  created_at          timestamptz not null default now()
);
-- 금칙어 검사는 assert_clean()으로 RPC에서 한다(SV3).

-- ---------------------------------------------------------------------------
-- posts: 공동구매 모집 글
-- ---------------------------------------------------------------------------
create table public.posts (
  id               uuid primary key default gen_random_uuid(),
  host_id          uuid        not null references public.profiles (id),
  zone_id          smallint    not null references public.zones (id),
  category_id      smallint    not null references public.categories (id),
  store_name       text        not null check (char_length(store_name) between 1 and 30),
  store_url        text        check (store_url is null
                                      or (store_url like 'https://%' and char_length(store_url) <= 500)),
  pickup_place_id  smallint    not null,
  pickup_note      text        check (pickup_note is null or char_length(pickup_note) <= 50),
  max_members      smallint    not null check (max_members between 2 and 8),  -- 방장 포함
  member_count     smallint    not null default 1,                            -- RPC만 갱신
  deadline_at      timestamptz not null,
  fee_note         text        check (fee_note is null or char_length(fee_note) <= 100),
  memo             text        check (memo is null or char_length(memo) <= 500),
  status           public.post_status not null default 'open',
  closed_at        timestamptz,
  completed_at     timestamptz,
  canceled_at      timestamptz,
  pay_due_at       timestamptz,  -- 마감 시 closed_at + 30분. 마감 전에는 null
  pay_reminded_at  timestamptz,  -- 송금 기한 임박 알림 발송 시각(중복 방지)
  hidden_at        timestamptz,  -- 신고 누적 자동 숨김
  created_at       timestamptz not null default now(),

  foreign key (pickup_place_id, zone_id) references public.pickup_places (id, zone_id),
  constraint posts_member_count_range check (member_count between 0 and max_members),
  -- 생성 시점 기준 10분 ~ 3시간 뒤 (create_post의 deadline_minutes 10~180과 같다)
  constraint posts_deadline_window check (deadline_at between created_at + interval '10 minutes'
                                                           and created_at + interval '3 hours')
);

create index posts_feed_idx on public.posts (zone_id, deadline_at)
  where status = 'open' and hidden_at is null;
create index posts_host_idx on public.posts (host_id, created_at desc);

-- ---------------------------------------------------------------------------
-- participants
-- 나갔다가 다시 참여하면 기존 행의 state를 joined로 되돌린다(kicked는 재참여 불가: RPC에서 검사).
-- ---------------------------------------------------------------------------
create table public.participants (
  post_id               uuid not null references public.posts (id) on delete cascade,
  user_id               uuid not null references public.profiles (id),
  role                  public.participant_role  not null default 'member',
  state                 public.participant_state not null default 'joined',
  paid_state            public.paid_state        not null default 'none',
  paid_at               timestamptz,  -- 마지막으로 sent가 된 시각
  muted                 boolean not null default false,
  last_read_message_id  bigint  not null default 0,
  joined_at             timestamptz not null default now(),
  left_at               timestamptz,
  primary key (post_id, user_id),
  -- 방장은 항상 paid_state = 'none'
  constraint participants_host_unpaid check (role <> 'host' or paid_state = 'none')
);

create index participants_user_idx on public.participants (user_id) where state = 'joined';

-- ---------------------------------------------------------------------------
-- messages
-- ---------------------------------------------------------------------------
create table public.messages (
  id             bigint generated always as identity primary key,  -- 커서 페이지네이션 기준
  post_id        uuid not null references public.posts (id) on delete cascade,
  sender_id      uuid references public.profiles (id) on delete set null,  -- 시스템 메시지는 null
  type           public.message_type not null default 'text',
  body           text not null check (char_length(body) between 1 and 1000),
  client_msg_id  uuid,  -- 중복 전송 방지 키
  hidden_at      timestamptz,
  created_at     timestamptz not null default now(),
  unique (sender_id, client_msg_id)
);

create index messages_room_idx on public.messages (post_id, id desc);

-- ---------------------------------------------------------------------------
-- RLS: 모든 테이블에 켠다(정책은 SV3+)
-- ---------------------------------------------------------------------------
alter table public.zones         enable row level security;
alter table public.categories    enable row level security;
alter table public.pickup_places enable row level security;
alter table public.profiles      enable row level security;
alter table public.posts         enable row level security;
alter table public.participants  enable row level security;
alter table public.messages      enable row level security;
